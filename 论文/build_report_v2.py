para('这是 GraphRAG 中「Graph」的核心。系统将命中的法条（node_type 为 Article）作为种子进入 Neo4j，沿两类精选边扩展关联条款：')
bullet('引用边：双向一跳（A 依照 B 或 B 依照 A），赋固定高权重（3.0），因直接法条引用属强相关；')
