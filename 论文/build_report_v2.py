h('5.1 混合召回与 RRF 融合', 2)
para('查询 q 同时进入两条召回通道，各取候选（默认每路 50 条）：稠密通道经 BGE-M3 将 q 嵌入后在 Chroma 中检索，'
     '以「1 − 距离」作相似度；稀疏通道经 jieba 分词后由 BM25 打分，仅保留得分为正的候选。两路均在子块粒度上进行。'
     '融合不采用分数直接相加（BM25 分与余弦相似度量纲不可比），而采用倒数排名融合（Reciprocal Rank Fusion, RRF, k=60）：')
code_block('score(d) = alpha / (k + rank_dense(d))  +  (1 − alpha) / (k + rank_sparse(d))')
para('其中 alpha 为稠密权重、(1 − alpha) 为稀疏权重。RRF 只依赖排名而与量纲无关，天然规避了两路分数不可比的问题。'
     '第六章的 alpha 扫描实验表明，本领域最优 alpha ≈ 0.9（显著偏稠密侧），原因是大量地方办法照抄国家条例导致语料高度同质，'
     '稀疏关键词路会稀释权威条文。dense / sparse 单模式则跳过融合、直接使用单路排名，其中 sparse 模式不调用任何嵌入接口，'
     '可作为零成本降级演示。')

h('5.2 召回期时效过滤', 2)
para('时效过滤并非检索后的独立后处理，而是前置嵌入在召回环节：开启「仅现行有效」时，稠密路将条件 {时效性:现行有效} '
     '直接下推到 Chroma 的库层查询，稀疏路则在收集候选时逐条筛除。如此，已废止/未生效条文在召回阶段即不占候选名额，'
     '从源头降低「引用失效依据」的风险。')

