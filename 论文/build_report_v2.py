def _set_cn(run, cn=CN_BODY, en='Times New Roman'):
    run.font.name = en
    run._element.rPr.rFonts.set(qn('w:eastAsia'), cn)


def h(text, level=1):
    p = doc.add_heading('', level=level)
    r = p.add_run(text)
    _set_cn(r, CN_HEAD, 'Times New Roman')
    r.font.color.rgb = RGBColor(0, 0, 0)
    if level == 1:
        r.font.size = Pt(16)
    elif level == 2:
        r.font.size = Pt(14)
    else:
        r.font.size = Pt(13)
    return p


def para(text, indent=True, bold=False, size=12, align=None):
    p = doc.add_paragraph()
    if indent:
        p.paragraph_format.first_line_indent = Pt(24)
    if align is not None:
        p.alignment = align
    r = p.add_run(text)
    _set_cn(r)
    r.font.size = Pt(size)
    r.bold = bold
    return p


def bullet(text):
    p = doc.add_paragraph(style='List Bullet')
    p.paragraph_format.first_line_indent = Pt(0)
    r = p.add_run(text)
    _set_cn(r)
    r.font.size = Pt(12)
    return p


def code_block(text):
    p = doc.add_paragraph()
    p.paragraph_format.left_indent = Pt(18)
    for i, line in enumerate(text.strip('\n').split('\n')):
        if i:
            p.add_run().add_break()
        r = p.add_run(line)
        r.font.name = 'Consolas'
        r._element.rPr.rFonts.set(qn('w:eastAsia'), CN_BODY)
        r.font.size = Pt(10.5)
    return p


def table(headers, rows, widths=None):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = 'Light Grid Accent 1'
    t.alignment = WD_ALIGN_PARAGRAPH.CENTER
    for j, htext in enumerate(headers):
        c = t.rows[0].cells[j]
        c.paragraphs[0].alignment = WD_ALIGN_PARAGRAPH.CENTER
        r = c.paragraphs[0].add_run(htext)
        _set_cn(r, CN_HEAD)
        r.font.size = Pt(10.5)
        r.bold = True
    for row in rows:
        cells = t.add_row().cells
        for j, val in enumerate(row):
            cells[j].paragraphs[0].alignment = WD_ALIGN_PARAGRAPH.CENTER
            r = cells[j].paragraphs[0].add_run(str(val))
            _set_cn(r)
            r.font.size = Pt(10.5)
    doc.add_paragraph()
    return t


