_DEPT_SUFFIX = ("部门", "局", "委", "机构", "机关", "厅", "部", "委员会",
                "管委会", "主管部门", "主管机构", "管理部门", "管理局", "管理委员会")
_NEVER_CANON = set(ACTOR_SEEDS)   # 种子本身即规范名，受保护不被部门规则改写


def _canon_dept(name):
    """部门类归一：命中关键词+部门后缀 → 规范部门名；否则返回 None(不改)。"""
    if not name.endswith(_DEPT_SUFFIX):
        return None
    for kws, canonical in DEPT_RULES:
        if any(k in name for k in kws):
            return canonical
    return None


def canon(name):
    """归一到规范名。返回 "" 表示应丢弃该实体。
    顺序：strip → 精确别名表 → 机型归并 → 部门规则 → 原样。"""
    name = (name or "").strip()
    if not name:
        return name
    if name in _NEVER_CANON:        # 种子=规范名,直接返回
        return name
    if name in ALIASES:
        return ALIASES[name]
    if name in DRONE_CATEGORY_CANON:
        return DRONE_CATEGORY_CANON[name]
    dept = _canon_dept(name)
    if dept is not None:
        return dept
    return name


